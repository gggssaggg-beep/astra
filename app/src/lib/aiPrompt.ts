/**
 * Единый ПОЛНЫЙ промпт для внешней ИИ (кнопка «Промпт для ИИ» рядом с «Обсудить
 * с Claude», просьба владелицы 2026-07-07). Тот же корректный контекст, что уходит
 * Клоду: правила верного расчёта + система домов пользователя + все позиции
 * (в знаке+градусе, с домом) + все аспекты рассматриваемых карт. Индивидуально
 * для каждого окна — лишнего не тащим (экономия токенов пользователя).
 */

const CALC_RULES =
  'Данные УЖЕ рассчитаны в приложении по Swiss Ephemeris (тропический зодиак, '
  + 'расчёт в UTC, аспект — интервал вход→точно→выход орбиса). Числам можно '
  + 'доверять: проверки выполнены (элонгации Меркурия <28° и Венеры <48° от '
  + 'Солнца соблюдены; углы через кратчайшую дугу с переходом через 0° Овна). '
  + 'Ниже, помимо читаемых позиций, даны ТОЧНЫЕ ЧИСЛА — эклиптические долготы '
  + '(0–360°), скорости (°/сут, «−» = ретроград) и куспиды домов. Можешь '
  + 'опираться на них для СОБСТВЕННЫХ расчётов (дополнительные и минорные '
  + 'аспекты, средние точки/мидпойнты, попадание градуса в дом, орбисы), если '
  + 'это углубит разбор. Приоритет — трактовать понятным, бытовым языком.';

export interface PromptPerson {
  name: string;
  birth: string;          // «23.03.1989 · 02:40 · Asia/Novosibirsk · Новосибирск»
  positions: string;      // «Солнце 2°09′ Овна (I дом ℞?)…»
  houses?: string;        // «I 5°Овна (упр. Марс)…» — если есть
  raw?: string;           // точные числа для расчётов ИИ: «Солнце 2.152° v=+0.98; …»
}

export interface AstroPrompt {
  title: string;
  kind: 'natal' | 'synastry' | 'transitNatal' | 'triple' | 'day' | 'aspect';
  houseSystem?: string;   // человекочитаемое название системы домов
  people?: PromptPerson[];
  // housesOwner — чьи дома проставлены у транзитных планет (дома считаются
  // только для внутренней карты A, в тройной их надо назвать явно)
  transit?: { label: string; positions: string; raw?: string; housesOwner?: string };
  aspects?: string[];     // строки аспектов рассматриваемой карты
  // Ближайшие ТОЧНЫЕ транзиты — уже посчитаны приложением (lib/forecast.ts).
  // Отдаём датами, чтобы ИИ их не выдумывала: «какие дни активны» — это они.
  forecast?: { span: string; items: string[] };
  focus?: string;         // конкретный аспект/вопрос, если окно — про один аспект
  extra?: string;         // доп. пояснение по типу карты
}

/** Собрать полный текст промпта. Пустые секции опускаются — токены не тратятся. */
export function buildAstroPrompt(p: AstroPrompt): string {
  const L: string[] = [];
  L.push(`Ты — вдумчивый астролог. Разбери: ${p.title}.`);
  L.push(CALC_RULES);
  if (p.houseSystem) L.push(`Система домов: ${p.houseSystem} (выбрана пользователем).`);
  if (p.extra) L.push(p.extra);

  for (const per of p.people ?? []) {
    L.push(`\n=== ${per.name} ===\nРождение: ${per.birth}.`);
    L.push(`Положения: ${per.positions}.`);
    if (per.houses) L.push(`Дома (куспиды и управители): ${per.houses}.`);
    if (per.raw) L.push(`Точные числа (долгота°/скорость): ${per.raw}.`);
  }
  if (p.transit) {
    L.push(`\n=== Транзит (небо на ${p.transit.label}) ===\n${p.transit.positions}.`);
    if (p.transit.housesOwner) L.push(`Дома у транзитных планет — по натальной карте ${p.transit.housesOwner}.`);
    if (p.transit.raw) L.push(`Точные числа (долгота°/скорость): ${p.transit.raw}.`);
  }
  if (p.aspects?.length) {
    L.push(`\n=== Аспекты ===\n${p.aspects.join('; ')}.`);
    L.push('Каждый аспект помечен весом (сильный/средний/фоновый) по тесноте орбиса. '
      + 'Разбирай сначала сильные, потом средние; фоновые — одной фразой, без глубокого разбора.');
  }
  if (p.forecast?.items.length) {
    L.push(`\n=== Ближайшие ТОЧНЫЕ транзиты (${p.forecast.span}) ===\n`
      + `Даты рассчитаны приложением и верны — бери их как есть.\n${p.forecast.items.join('; ')}.`);
  }
  if (p.focus) L.push(`\nВ фокусе: ${p.focus}.`);

  // Расширенный разбор — только для карт с транзитом (положения по домам натала,
  // транзит→натал/куспиды, ингрессии, конфигурации, мидпойнты имеют смысл именно
  // при транзите). Просьба владелицы 2026-07-25.
  // 2026-07-26: часть этого приложение уже считает точно (дома транзитных планет,
  // направление, окна, даты пиков) — теперь они ДАНЫ выше, а ИИ прямо запрещено
  // пересчитывать их «на глаз»: раньше она их выдумывала.
  if (p.transit) L.push('\nЧАСТЬ РАБОТЫ УЖЕ СДЕЛАНА ПРИЛОЖЕНИЕМ (Swiss Ephemeris): дома '
    + 'транзитных планет, орбисы, направление (сходится/расходится), окна аспектов '
    + '(вход в орбис → точно → выход) и даты ближайших точных транзитов даны выше — это '
    + 'верные числа. НЕ пересчитывай и не заменяй их своими прикидками. Собери из них в '
    + 'выводе: положения транзитных планет по домам натальной карты; аспекты транзит → '
    + 'натал с орбисами и окнами; отдельно списком — сходящиеся и расходящиеся. Добавь от '
    + 'себя то, чего выше нет: минорные аспекты, аспекты транзит ↔ куспиды домов (Asc, MC и '
    + 'остальные), замкнутые конфигурации (тау-квадраты, большие трины, йоды, бисекстили), '
    + 'средние точки (мидпойнты), задетые транзитами, и сроки ингрессий (переходов планет '
    + 'через куспиды домов). Считай их по точным долготам и скоростям выше и помечай как '
    + 'приблизительные.');

  L.push('\nПиши по-русски, ясно и по делу, переводи всё на бытовой язык — '
    + 'простыми словами, без заумных терминов. '
    + 'Дай цельную картину: главные темы, сильные и напряжённые места, на что обратить внимание.');
  return L.join('\n');
}

