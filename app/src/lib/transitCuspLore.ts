/**
 * Транзит планеты к куспиду натального дома. В отличие от натального
 * `PLANET_CUSP_LORE` (планета КАРТЫ у куспида — постоянная окраска дома), здесь
 * ПРОХОДЯЩАЯ планета временно активирует тему дома. Текст композиционный (как
 * любит владелица): характер транзитной планеты × тема дома × тон аспекта.
 * Бытовой язык, на «ты».
 */
import { HOUSE_THEME } from './houseThemes.ts';

/** Что приносит проходящая планета в задетую тему. */
const TRANSIT_FLAVOR: Record<string, string> = {
  'Солнце': 'Солнце на пару дней ставит эту тему в центр — она подсвечена и просит внимания.',
  'Луна': 'Луна подсвечивает тему всего на день-два: настроение, чувства, быт — коротко, но заметно.',
  'Меркурий': 'Меркурий заводит сюда разговоры, новости, бумаги и короткие поездки.',
  'Венера': 'Венера приносит мягкость, деньги, симпатии и тягу к красоте.',
  'Марс': 'Марс добавляет энергии и напора — можно продавить дело, а можно вспыхнуть на ровном месте.',
  'Юпитер': 'Юпитер расширяет тему: возможности и рост, но и соблазн переоценить.',
  'Сатурн': 'Сатурн уплотняет и проверяет тему: ответственность и рамки, зато результат надолго.',
  'Уран': 'Уран встряхивает тему: неожиданности, свобода, резкие повороты.',
  'Нептун': 'Нептун размывает границы темы: мечты и вдохновение, но и туман — легко обмануться.',
  'Раху': 'Раху тянет сюда с силой — усиливает голод и притяжение к теме, порой через край.',
  'Кету': 'Кету, наоборот, отстраняет от темы — тянет отпустить, обесценить, уйти внутрь.',
};

/** Глагол + совет по тону аспекта. */
const ASPECT_TAKE: Record<string, { verb: string; advice: string }> = {
  'соединение': { verb: 'сходится с', advice: 'Тема включается в полную силу — прямое попадание.' },
  'секстиль': { verb: 'мягко поддерживает', advice: 'Дверь приоткрыта: небольшое усилие — и тема идёт легко.' },
  'трин': { verb: 'легко течёт к', advice: 'Складывается почти само — можно спокойно опереться.' },
  'квадрат': { verb: 'давит на', advice: 'Тема под нажимом: трение подталкивает действовать, но нервно.' },
  'оппозиция': { verb: 'встаёт напротив', advice: 'Тему тянет в две стороны — нужен баланс, часто через других людей.' },
};

/** Текст транзита к куспиду: характер планеты × тема дома × тон аспекта. */
export function transitCuspText(planet: string, cusp: number, aspect: string): string {
  const flavor = TRANSIT_FLAVOR[planet] ?? '';
  const theme = HOUSE_THEME[cusp] ?? '';
  const t = ASPECT_TAKE[aspect] ?? { verb: 'задевает', advice: '' };
  return `Транзитная ${planet} ${t.verb} куспид ${cusp}-го дома — темы «${theme}». ${flavor} ${t.advice}`.trim();
}
