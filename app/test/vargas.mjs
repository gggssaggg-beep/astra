/**
 * Варги (lib/vargas.ts) — БЕЗ WASM: всё считается от знака и градуса.
 *
 * Эталон — тот же эталон А, что и в test/vedicmath.mjs:
 * долготы взяты с экрана профессиональной джйотиш-программой, знаки варг посчитаны
 * вручную по правилам Парашары. Если тест красный — ошибка в коде, не в
 * эталонах.
 *
 * Запуск:  node test/vargas.mjs
 */
import assert from 'node:assert/strict';
import {
  d2Sign, d3Sign, d7Sign, d10Sign, d12Sign, d30Sign,
  vargaSignOf, vargaSignAt, vargaInfo, VARGA_LIST,
} from '../src/lib/vargas.ts';
import { navamshaSign } from '../src/lib/vedic.ts';

let n = 0;
const ok = (name, fn) => { fn(); n++; console.log(`  ✓ ${name}`); };
const Z = ['Овен', 'Телец', 'Близнецы', 'Рак', 'Лев', 'Дева',
  'Весы', 'Скорпион', 'Стрелец', 'Козерог', 'Водолей', 'Рыбы'];
/** «28°03′02″ Водолей» → долгота */
const at = (sign, d, m, s) => Z.indexOf(sign) * 30 + d + m / 60 + s / 3600;
/** знак варги по долготе: функция варги от (знак, градус в знаке) */
const V = (fn, lon) => Z[fn(Math.floor(lon / 30), lon % 30)];

const CHART = {
  'Солнце': at('Водолей', 28, 3, 2),
  'Луна': at('Лев', 22, 25, 21),
  'Марс': at('Рыбы', 12, 20, 55),
  'Меркурий': at('Рыбы', 13, 47, 59),
  'Юпитер': at('Водолей', 14, 51, 13),
  'Венера': at('Козерог', 12, 34, 46),
  'Сатурн': at('Рыбы', 25, 35, 6),
};
const ASC = at('Дева', 0, 6, 57);
const L = { ...CHART, 'Асцендент': ASC };

/** Общий прогон списка эталонов «кто → какой знак» через функцию варги. */
const table = (fn, cases) => {
  for (const [who, sign] of cases) {
    ok(`${who} → ${sign}`, () => assert.equal(V(fn, L[who]), sign));
  }
};

console.log('=== D2 хора (половины по 15°: Лев или Рак) ===');
{
  table(d2Sign, [
    ['Солнце', 'Рак'],      // Водолей (нечётный) 28°03′ — вторая половина
    ['Луна', 'Рак'],        // Лев (нечётный) 22°25′
    ['Марс', 'Рак'],        // Рыбы (чётный) 12°21′ — первая половина
    ['Сатурн', 'Лев'],      // Рыбы (чётный) 25°35′
    ['Венера', 'Рак'],      // Козерог (чётный) 12°35′
    ['Асцендент', 'Рак'],   // Дева (чётный) 0°07′
  ]);
  ok('в хоре только два знака — Лев и Рак', () => {
    for (let si = 0; si < 12; si++) {
      for (const d of [0, 7.5, 14.9, 15, 22, 29.99]) {
        assert.ok([3, 4].includes(d2Sign(si, d)), `знак ${si}, градус ${d}`);
      }
    }
  });
  ok('ровно 15° нечётного знака — уже вторая половина, Рак', () =>
    assert.equal(Z[d2Sign(0, 15)], 'Рак'));
  ok('нечётный знак начинает со Льва, чётный — с Рака', () => {
    assert.equal(Z[d2Sign(0, 0)], 'Лев');     // Овен
    assert.equal(Z[d2Sign(1, 0)], 'Рак');     // Телец
    assert.equal(Z[d2Sign(1, 20)], 'Лев');
  });
}

console.log('=== D3 дреккана (трети по 10°: 1-й, 5-й, 9-й от знака) ===');
{
  table(d3Sign, [
    ['Солнце', 'Весы'],       // Водолей, третья треть → 9-й от него
    ['Луна', 'Овен'],         // Лев, третья треть
    ['Марс', 'Рак'],          // Рыбы, вторая треть → 5-й от него
    ['Венера', 'Телец'],      // Козерог, вторая треть
    ['Асцендент', 'Дева'],    // Дева, первая треть → сам знак
  ]);
  ok('Овен: 5° → Овен, 15° → Лев, 25° → Стрелец (тригон стихии)', () => {
    assert.equal(Z[d3Sign(0, 5)], 'Овен');
    assert.equal(Z[d3Sign(0, 15)], 'Лев');
    assert.equal(Z[d3Sign(0, 25)], 'Стрелец');
  });
  ok('границы третей ровные: 10° — уже вторая, 20° — третья', () => {
    assert.equal(Z[d3Sign(0, 9.99)], 'Овен');
    assert.equal(Z[d3Sign(0, 10)], 'Лев');
    assert.equal(Z[d3Sign(0, 20)], 'Стрелец');
  });
}

console.log('=== D7 саптамша (7 частей по 4°17′) ===');
{
  table(d7Sign, [
    ['Солнце', 'Лев'],        // Водолей (нечётный), 7-я часть → от себя
    ['Луна', 'Козерог'],      // Лев (нечётный), 6-я часть
    ['Асцендент', 'Рыбы'],    // Дева (чётный) 0°07′ → счёт от 7-го, т.е. с Рыб
  ]);
  ok('нечётный знак считает от себя, чётный — от 7-го от себя', () => {
    assert.equal(Z[d7Sign(0, 1)], 'Овен');        // Овен нечётный
    assert.equal(Z[d7Sign(1, 1)], 'Скорпион');    // Телец чётный → 7-й от него
  });
  ok('последняя, 7-я часть Овна — Весы (0+6)', () =>
    assert.equal(Z[d7Sign(0, 29)], 'Весы'));
}

console.log('=== D10 дашамша (10 частей по 3°) ===');
{
  table(d10Sign, [
    ['Солнце', 'Скорпион'],   // Водолей (нечётный), 10-я часть
    ['Луна', 'Рыбы'],         // Лев (нечётный), 8-я часть
    ['Марс', 'Рыбы'],         // Рыбы (чётный) → счёт со Скорпиона, 5-я часть
    ['Меркурий', 'Рыбы'],     // Рыбы (чётный), та же 5-я часть
    ['Сатурн', 'Рак'],        // Рыбы (чётный), 9-я часть
    ['Асцендент', 'Телец'],   // Дева (чётный) 0°07′ → счёт с 9-го, т.е. с Тельца
  ]);
  ok('нечётный знак считает от себя, чётный — от 9-го от себя', () => {
    assert.equal(Z[d10Sign(0, 1)], 'Овен');       // Овен нечётный
    assert.equal(Z[d10Sign(1, 1)], 'Козерог');    // Телец чётный → 9-й от него
  });
  ok('шаг ровно 3°: 2°59′ — первая часть, 3°01′ — вторая', () => {
    assert.equal(Z[d10Sign(0, 2 + 59 / 60)], 'Овен');
    assert.equal(Z[d10Sign(0, 3 + 1 / 60)], 'Телец');
  });
}

console.log('=== D12 двадашамша (12 частей по 2°30′, счёт от самого знака) ===');
{
  table(d12Sign, [
    ['Солнце', 'Козерог'],    // Водолей, 12-я часть
    ['Луна', 'Овен'],         // Лев, 9-я часть
    ['Асцендент', 'Дева'],    // Дева, первая часть → сам знак
  ]);
  ok('ровно 2°30′ — уже вторая часть (Овен → Телец)', () => {
    assert.equal(Z[d12Sign(0, 2.49)], 'Овен');
    assert.equal(Z[d12Sign(0, 2.5)], 'Телец');
  });
  ok('чётность знака роли не играет: и Овен, и Телец начинают с себя', () => {
    assert.equal(Z[d12Sign(0, 0)], 'Овен');
    assert.equal(Z[d12Sign(1, 0)], 'Телец');
  });
  ok('последняя часть замыкает круг: 29° Овна → Рыбы', () =>
    assert.equal(Z[d12Sign(0, 29)], 'Рыбы'));
}

console.log('=== D30 тримшамша (неравные доли, знак даёт планета) ===');
{
  table(d30Sign, [
    ['Солнце', 'Весы'],       // Водолей (нечётный) 28°03′ → Венера
    ['Луна', 'Близнецы'],     // Лев (нечётный) 22°25′ → Меркурий
    ['Марс', 'Рыбы'],         // Рыбы (чётный) 12°21′ → Юпитер
    ['Сатурн', 'Скорпион'],   // Рыбы (чётный) 25°35′ → Марс
    ['Венера', 'Рыбы'],       // Козерог (чётный) 12°35′ → Юпитер
  ]);
  ok('нечётный знак: 5 Марс · 5 Сатурн · 8 Юпитер · 7 Меркурий · 5 Венера', () => {
    assert.deepEqual([2, 7, 14, 20, 27].map((d) => Z[d30Sign(0, d)]),
      ['Овен', 'Водолей', 'Стрелец', 'Близнецы', 'Весы']);
  });
  ok('чётный знак: 5 Венера · 7 Меркурий · 8 Юпитер · 5 Сатурн · 5 Марс', () => {
    assert.deepEqual([2, 7, 14, 22, 27].map((d) => Z[d30Sign(1, d)]),
      ['Телец', 'Дева', 'Рыбы', 'Козерог', 'Скорпион']);
  });
  ok('ровно 5° нечётного знака — уже доля Сатурна (Водолей)', () => {
    assert.equal(Z[d30Sign(0, 4.99)], 'Овен');
    assert.equal(Z[d30Sign(0, 5)], 'Водолей');
  });
  ok('ровно 12° чётного знака — уже доля Юпитера (Рыбы)', () => {
    assert.equal(Z[d30Sign(1, 11.99)], 'Дева');
    assert.equal(Z[d30Sign(1, 12)], 'Рыбы');
  });
  ok('в тримшамше не бывает знаков светил (Рак и Лев)', () => {
    for (let si = 0; si < 12; si++) {
      for (let d = 0; d < 30; d += 0.5) {
        assert.ok(![3, 4].includes(d30Sign(si, d)), `знак ${si}, градус ${d}`);
      }
    }
  });
}

console.log('=== список варг и общий доступ ===');
{
  ok('VARGA_LIST — 8 карт в порядке D1, D9, D2, D3, D7, D10, D12, D30', () =>
    assert.deepEqual(VARGA_LIST.map((v) => v.id),
      ['d1', 'd9', 'd2', 'd3', 'd7', 'd10', 'd12', 'd30']));
  ok('у каждой карты есть подпись и тема', () =>
    VARGA_LIST.forEach((v) => {
      assert.ok(v.label.startsWith(v.id.toUpperCase() + ' '), v.id);
      assert.ok(v.theme.length > 2, v.id);
    }));
  ok('темы канонические: D10 карьера, D7 дети, D12 родители, D30 испытания', () => {
    assert.equal(vargaInfo('d10').theme, 'карьера');
    assert.equal(vargaInfo('d7').theme, 'дети');
    assert.equal(vargaInfo('d12').theme, 'родители');
    assert.equal(vargaInfo('d30').theme, 'испытания');
  });
  ok('vargaSignOf(d1) — просто знак', () => {
    assert.equal(vargaSignOf('d1', 10, 28), 10);
    assert.equal(Z[vargaSignAt('d1', CHART['Сатурн'])], 'Рыбы');
  });
  ok('vargaSignOf(d9) совпадает с навамшей из lib/vedic.ts', () => {
    for (const lon of Object.values(L)) {
      assert.equal(vargaSignAt('d9', lon), navamshaSign(lon));
    }
  });
  ok('навамша Асцендента — Козерог (эталон профессиональной программой)', () =>
    assert.equal(Z[vargaSignAt('d9', ASC)], 'Козерог'));
  ok('vargaSignOf зовёт нужную таблицу для каждой варги', () => {
    const si = 10, deg = 28.05;   // Солнце: Водолей 28°03′
    assert.equal(vargaSignOf('d2', si, deg), d2Sign(si, deg));
    assert.equal(vargaSignOf('d3', si, deg), d3Sign(si, deg));
    assert.equal(vargaSignOf('d7', si, deg), d7Sign(si, deg));
    assert.equal(vargaSignOf('d10', si, deg), d10Sign(si, deg));
    assert.equal(vargaSignOf('d12', si, deg), d12Sign(si, deg));
    assert.equal(vargaSignOf('d30', si, deg), d30Sign(si, deg));
  });
  ok('любая варга любой долготы даёт знак 0..11', () => {
    for (const v of VARGA_LIST) {
      for (let lon = 0; lon < 360; lon += 0.37) {
        const s = vargaSignAt(v.id, lon);
        assert.ok(Number.isInteger(s) && s >= 0 && s <= 11, `${v.id} @ ${lon} → ${s}`);
      }
    }
  });
}

console.log(`\n✅ варги: ${n} проверок пройдено`);
