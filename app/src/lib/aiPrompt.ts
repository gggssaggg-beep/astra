/** Хвост промпта под выбранный фокус. 'general' (и пустой свой вопрос) — пусто. */
export function focusBlock(id: FocusId, question = ''): string {
  if (id === 'general') return '';
  if (id === 'custom') {
    const q = question.trim();
    if (!q) return '';
    return `\n\nФОКУС РАЗБОРА: конкретный вопрос — «${q}». Разверни разбор вокруг него: какие `
      + 'астрологические факторы поддерживают развитие ситуации, какие создают препятствия, что '
      + 'здесь внутренний процесс, а что может стать внешним событием.\n' + DEEP_TAIL;
  }
  return `\n\n${FOCUS_TEXT[id]}\n${DEEP_TAIL}`;
}
