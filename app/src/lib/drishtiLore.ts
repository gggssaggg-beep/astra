/** Расстояние от знака грахи до знака цели, включительно: свой знак = 1. */
export const distanceOf = (fromSign: number, toSign: number): number =>
  ((toSign - fromSign) % 12 + 12) % 12 + 1;

/** Домами какого дома управляет граха в этой карте (факт, не оценка). */
export function rulesHouses(graha: string, lagnaSign: number): number[] {
  const out: number[] = [];
  SIGN_LORDS.forEach((lord, si) => {
    if (lord === graha) out.push(((si - lagnaSign) % 12 + 12) % 12 + 1);
  });
  return out.sort((a, b) => a - b);
}

/** Составное отношение смотрящего к тому, на кого он смотрит. null — узлы. */
export function relationBetween(
  from: string, to: string, fromSign: number, toSign: number,
): Relation | null {
  const nat = naturalRelation(from, to);
  if (!nat) return null;
  return compoundRelation(nat, temporalRelation(fromSign, toSign));
}

const HOUSE_ORD = (h: number) => `${h}-й`;

/**
 * Дришти в кундали: что даёт взгляд грахи дому, и что — тем, кто в нём стоит.
 *
 * @param from     кто смотрит
 * @param house    дом-цель, 1..12
 * @param distance расстояние взгляда (7 — обычный, прочие — особые)
 * @param hits     грахи, стоящие в этом знаке (могут быть пустыми)
 * @param signs    знаки грах — нужны для отношений (имя → знак)
 */
export function drishtiText(
  from: string, house: number, distance: number,
  hits: string[] = [], signs: Record<string, number> = {},
): string {
  const parts: string[] = [];
  if (GAZE[from]) parts.push(GAZE[from]);
  if (BHAVA_THEME[house]) {
    parts.push(`Здесь это ${HOUSE_ORD(house)} дом — ${BHAVA_THEME[house]}.`);
  }
  const sp = SPECIAL[from]?.[distance];
  if (sp) parts.push(sp);

  for (const h of hits) {
    if (h === from) continue;
    const rel = signs[from] != null && signs[h] != null
      ? relationBetween(from, h, signs[from], signs[h]) : null;
    parts.push(rel
      ? `Под взглядом стоит ${h} — по отношению к нему ${from} здесь ${RELATION_LABEL[rel]}: `
        + `взгляд ложится ${rel === 'greatFriend' || rel === 'friend' ? 'по-доброму' : rel === 'neutral' ? 'ровно' : 'тяжело'}.`
      : `Под взглядом стоит ${h}.`);
  }
  return parts.join(' ');
}

/**
 * Дришти ГОЧАРЫ: идущая граха смотрит на граху кундали. Собирается из того, что
 * астролог назвал сам: манера взгляда, дружба или вражда, идёт ли сейчас период
 * этой грахи и какими домами она в карте управляет.
 *
 * @param dashaLords какие грахи ведут период сейчас (маха и антар) — по ним
 *                   решаем, «горячий» ли это взгляд для человека прямо сейчас
 */
export function gocharaDrishtiText(
  from: string, to: string, toHouse: number,
  fromSign: number, toSign: number,
  lagnaSign: number, dashaLords: string[] = [],
): string {
  const parts: string[] = [];
  if (GAZE[from]) parts.push(GAZE[from]);
  parts.push(`Взгляд ложится на ${to} в ${HOUSE_ORD(toHouse)} доме кундали — `
    + `${BHAVA_THEME[toHouse] ?? 'тема дома'}.`);

  const rel = relationBetween(from, to, fromSign, toSign);
  if (rel) {
    parts.push(rel === 'greatFriend' || rel === 'friend'
      ? `${from} здесь ${RELATION_LABEL[rel]} для ${to}: тема поднимается легче, чем обычно.`
      : rel === 'neutral'
        ? `${from} к ${to} сейчас нейтрален: взгляд заметен, но не решает.`
        : `${from} здесь ${RELATION_LABEL[rel]} для ${to}: тема идёт через сопротивление.`);
  }

  const rules = rulesHouses(to, lagnaSign);
  if (rules.length) {
    parts.push(`${to} в этой карте управляет ${rules.map(HOUSE_ORD).join(' и ')} домом — `
      + 'задет будет и он.');
  }

  const hot = dashaLords.filter((l) => l === from || l === to);
  if (hot.length) {
    parts.push(hot.length > 1
      ? `Сейчас идёт период обеих грах — взгляд попадает в самое живое место карты.`
      : `Сейчас идёт период ${hot[0]} — то, на что обычно не обратили бы внимания, `
        + 'сработает заметно.');
  } else {
    parts.push('Периода ни одной из них сейчас нет — взгляд проходит фоном.');
  }
  return parts.join(' ');
}
