/**
 * Вторая строка Луны — «Джатака Париджата» / «Сарвартха Чинтамани». Трактаты
 * тут честно расходятся (единственная строка, где это так), поэтому вариант не
 * выброшен: если Луна попала по нему — приложение скажет об этом отдельно и
 * назовёт трактат, а не выдаст один вариант за общий.
 */
export const MRITYU_MOON_PARIJATA: MrityuRow = [8, 25, 22, 22, 21, 1, 4, 23, 18, 20, 20, 10];

/** Какой трактат дал совпадение (важно только для Луны). */
export type MrityuVariant = 'phaladeepika' | 'parijata';

export const MRITYU_SOURCE: Record<MrityuVariant, string> = {
  phaladeepika: 'Пхаладипика',
  parijata: 'Джатака Париджата',
};

/**
 * Орбис в МИНУТАХ дуги — по д-ру К. С. Чараку. Мритью бхага это точка, а не
 * целый градус, поэтому важно, насколько близко граха подошла.
 * ⚠ Встречается и другое чтение: «весь табличный градус» (26° Луны = отрезок
 * 25°00′–26°00′). Оно шире нашего и ловит больше карт; какой вариант ближе
 * школе Георгия — вопрос к нему, меняется одной таблицей.
 */
export const MRITYU_ORB_MIN: Record<string, number> = {
  'Лагна': 60, 'Солнце': 40, 'Луна': 40, 'Меркурий': 40,
};
/** Все прочие грахи (Марс, Юпитер, Венера, Сатурн, Раху, Кету, Манди). */
export const MRITYU_ORB_MIN_DEFAULT = 30;

export const mrityuOrbMin = (name: string): number =>
  MRITYU_ORB_MIN[name] ?? MRITYU_ORB_MIN_DEFAULT;

export interface MrityuHit {
  name: string;
  /** знак, в котором стоит точка: 0 = Овен */
  signIndex: number;
  /** табличный критический градус */
  degree: number;
  /** фактический градус в знаке */
  deg: number;
  /** отклонение от точки в минутах дуги, со знаком (− не дошла, + прошла) */
  offMin: number;
  /** допуск, в пределах которого считаем попадание */
  orbMin: number;
  /** по какому трактату совпало (различается только у Луны) */
  variant: MrityuVariant;
}

const norm = (x: number): number => ((x % 360) + 360) % 360;

/** Табличный градус мритью бхаги для грахи в знаке. null — грахи нет в таблице. */
export function mrityuDegree(name: string, signIndex: number,
  variant: MrityuVariant = 'phaladeepika'): number | null {
  const row = name === 'Луна' && variant === 'parijata'
    ? MRITYU_MOON_PARIJATA : MRITYU_BHAGA[name];
  if (!row) return null;
  return row[((signIndex % 12) + 12) % 12];
}

/**
 * Попала ли точка в мритью бхагу. Проверяем основной трактат, а для Луны — и
 * второй: если совпало только по нему, вернём попадание с пометкой трактата.
 * Долгота — сидерическая (в тропической эти градусы не читаются).
 */
export function mrityuCheck(name: string, lon: number): MrityuHit | null {
  const l = norm(lon);
  const signIndex = Math.floor(l / 30);
  const deg = l - signIndex * 30;
  const orbMin = mrityuOrbMin(name);
  const variants: MrityuVariant[] = name === 'Луна' ? ['phaladeepika', 'parijata'] : ['phaladeepika'];
  for (const variant of variants) {
    const degree = mrityuDegree(name, signIndex, variant);
    if (degree == null) return null;
    const offMin = (deg - degree) * 60;
    if (Math.abs(offMin) <= orbMin) {
      return { name, signIndex, degree, deg, offMin, orbMin, variant };
    }
  }
  return null;
}

/** Все попадания среди переданных точек (грахи карты, лагна, Манди). */
export function mrityuHits(points: { name: string; lon: number }[]): MrityuHit[] {
  const out: MrityuHit[] = [];
  for (const p of points) {
    const hit = mrityuCheck(p.name, p.lon);
    if (hit) out.push(hit);
  }
  return out;
}

/** «19°58′ — мритью бхага Марса в Овне (19°), недобор 2′». */
export const mrityuLabel = (h: MrityuHit): string => {
  const off = Math.round(Math.abs(h.offMin));
  const where = off === 0 ? 'точно в градусе'
    : `${h.offMin < 0 ? 'не дошла' : 'прошла'} ${off}′`;
  return `${h.degree}° — ${where}`;
};
