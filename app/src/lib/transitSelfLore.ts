/**
 * Текст «кто движется, тот и задаёт смысл» + ритм транзитной планеты.
 * null, если планета вне корпуса (доп. объекты).
 */
export function transitRhythm(transitPlanet: string, natalPlanet: string): string | null {
  const r = RHYTHM[transitPlanet];
  if (!r) return null;
  const back = transitPlanet === natalPlanet ? ''
    : ` Обратный случай — ${transitAdj(natalPlanet)} ${natalPlanet} `
      + `по ${natalAdjDat(transitPlanet)} ${dative(transitPlanet)} — `
      + 'это ДРУГОЕ событие: свой ритм, свои даты, свои заметки.';
  return `Смысл задаёт та планета, которая движется: сейчас это ${transitPlanet}. ${r}${back}`;
}

/**
 * Транзитная планета к ДРУГОЙ натальной: рамка «небо задевает твоё» — чтобы
 * общий текст пары не читался как разбор двух людей.
 */
export function transitFrameText(tPlanet: string, nPlanet: string): string {
  const a = transitAdj(tPlanet);
  const adj = a[0].toUpperCase() + a.slice(1);
  const ng = genderOf(nPlanet);
  const your = ng === 'f' ? 'твою натальную' : ng === 'n' ? 'твоё натальное' : 'твой натальный';
  return `${adj} ${tPlanet} задевает ${your} ${accusative(nPlanet)} — небо временно `
    + `включает эту твою тему. Это не черта характера, а период: у аспекта есть `
    + `начало, пик и конец (окно выше).`;
}
