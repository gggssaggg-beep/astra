/** Полный текст по строке пады. `house` — дом пады от лагны, `sign` — знак пады. */
export function padaText(code: string, sign: number | null, house: number | null): string {
  const parts = [PADA_ROLE[code] ?? ''];
  if (sign != null) {
    if (code === 'A1' && AL_SIGN[sign]) parts.push(AL_SIGN[sign]);
    if (code === 'A12' && UL_SIGN[sign]) parts.push(UL_SIGN[sign]);
  }
  if (code === 'A1' && house != null && AL_HOUSE[house]) parts.push(AL_HOUSE[house]);
  return parts.filter(Boolean).join(' ');
}
