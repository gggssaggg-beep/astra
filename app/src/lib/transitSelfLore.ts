/**
 * Текст для «транзитная планета ↔ та же натальная планета».
 * null, если планета вне корпуса (доп. объекты) или аспект неизвестен —
 * тогда UI откатывается на общий смысл аспекта (ASPECT_LORE).
 */
export function transitSelfLore(planet: string, aspect: string): string | null {
  const cycle = CYCLE[planet];
  const phase = PHASE[aspect];
  if (!cycle || !phase) return null;
  return `${cycle} ${phase}`;
}

// ── Согласование по роду (иначе «Транзитный Луна… по натальному Меркурий») ──
/** Женский/средний род там, где правило по окончанию врёт (несклоняемые и т.п.). */
const GENDER: Record<string, 'f' | 'n' | 'm'> = {
  'Лилит': 'f', 'Раху': 'm', 'Кету': 'm', 'Солнце': 'n',
};
function genderOf(name: string): 'f' | 'n' | 'm' {
  const g = GENDER[name];
  if (g) return g;
  const last = name.slice(-1);
  if (last === 'а' || last === 'я') return 'f';
  if (last === 'о' || last === 'е') return 'n';
  return 'm';
}
/** Винительный падеж: «задевает твою натальную Венеру / твой натальный Марс». */
function accusative(name: string): string {
  if (GENDER[name] === 'f' && !/[ая]$/.test(name)) return name;   // Лилит — не склоняем
  if (/а$/.test(name)) return name.slice(0, -1) + 'у';            // Венера → Венеру
  if (/я$/.test(name)) return name.slice(0, -1) + 'ю';
  return name;   // муж. неодуш. и ср. род — как именительный
}

/** Дательный падеж: «по натальной Луне / по натальному Меркурию». */
function dative(name: string): string {
  if (name === 'Солнце') return 'Солнцу';                         // -це → -цу
  if (GENDER[name] && !/[аяое]$/.test(name)) return name;         // Раху/Кету/Лилит — не склоняем
  if (/[ая]$/.test(name)) return name.slice(0, -1) + 'е';         // Луна → Луне, Венера → Венере
  if (/ий$/.test(name)) return name.slice(0, -2) + 'ию';          // Меркурий → Меркурию
  if (/о$/.test(name)) return name.slice(0, -1) + 'у';
  if (/е$/.test(name)) return name.slice(0, -1) + 'ю';
  return name + 'у';                                              // Марс → Марсу
}

/** «транзитный / транзитная / транзитное» по роду планеты. */
const transitAdj = (name: string): string => {
  const g = genderOf(name);
  return g === 'f' ? 'транзитная' : g === 'n' ? 'транзитное' : 'транзитный';
};
/** «натальному / натальной» (дат. падеж) по роду планеты. */
const natalAdjDat = (name: string): string =>
  genderOf(name) === 'f' ? 'натальной' : 'натальному';

