/**
 * Тест часового пояса, заданного ЧИСЛОМ (правка астролога 2026-07-29: «нужно
 * добавить часовой пояс в формате GMT, у меня GMT+3 — по городу и стране не
 * находит»). Проверяет три вещи:
 *   1) разбор/сборка/подпись смещения («+03:00» ⇄ 180 ⇄ «GMT+3»);
 *   2) момент рождения считается по фиксированному смещению, БЕЗ перевода часов;
 *   3) числовой пояс и город дают РАЗНЫЙ момент там, где в истории был перевод
 *      часов, — ради этого астролог и просил ввод числом.
 *
 * Запуск: node test/fixedtz.mjs
 */
import { fixedTzMinutes, fixedTzId, tzLabel, tzValid } from '../src/lib/format.ts';
import { zonedTimeUTC } from '../src/lib/format.ts';

let ok = 0, bad = 0;
const eq = (name, got, exp) => {
  if (got === exp) { ok++; }
  else { bad++; console.log(`  БАГ  ${name}: ${got} ≠ ${exp}`); }
};

// 1. разбор
eq('+03:00', fixedTzMinutes('+03:00'), 180);
eq('+05:30 (Индия)', fixedTzMinutes('+05:30'), 330);
eq('+05:45 (Непал)', fixedTzMinutes('+05:45'), 345);
eq('-04:30', fixedTzMinutes('-04:30'), -270);
eq('+00:00', fixedTzMinutes('+00:00'), 0);
eq('город — не смещение', fixedTzMinutes('Europe/Moscow'), null);
eq('за пределами шкалы', fixedTzMinutes('+15:00'), null);
eq('мусор', fixedTzMinutes('GMT+3'), null);

// 2. сборка и подпись
eq('id 180', fixedTzId(180), '+03:00');
eq('id 330', fixedTzId(330), '+05:30');
eq('id -270', fixedTzId(-270), '-04:30');
eq('id 0', fixedTzId(0), '+00:00');
eq('подпись +3', tzLabel('+03:00'), 'GMT+3');
eq('подпись +5:30', tzLabel('+05:30'), 'GMT+5:30');
eq('подпись -4:30', tzLabel('-04:30'), 'GMT−4:30');
eq('город остаётся собой', tzLabel('Europe/Moscow'), 'Europe/Moscow');
eq('годен: смещение', tzValid('+03:00'), true);
eq('годен: город', tzValid('Europe/Moscow'), true);
eq('не годен', tzValid('Нижняя Пупыровка'), false);

// 3. момент рождения по фиксированному смещению
const t = (d, tm, tz) => zonedTimeUTC(d, tm, tz).toISOString();
eq('GMT+3 → UTC', t('1982-08-19', '10:36:00', '+03:00'), '1982-08-19T07:36:00.000Z');
eq('GMT+5:30 → UTC', t('1998-03-12', '00:15:00', '+05:30'), '1998-03-11T18:45:00.000Z');
eq('GMT-4:30 → UTC', t('2010-01-01', '02:00:00', '-04:30'), '2010-01-01T06:30:00.000Z');
// смещение не «переводит часы»: зима и лето считаются одинаково
eq('без DST зимой', t('2020-01-15', '12:00:00', '+02:00'), '2020-01-15T10:00:00.000Z');
eq('без DST летом', t('2020-07-15', '12:00:00', '+02:00'), '2020-07-15T10:00:00.000Z');
// а вот город переводит: в августе 1982 в Москве действовало летнее время (+4),
// поэтому «10:36 по Москве» — это НЕ то же, что «10:36 по GMT+3». Ради этого
// различия астролог и просил вводить смещение руками.
eq('город с переводом часов', t('1982-08-19', '10:36:00', 'Europe/Moscow'),
  '1982-08-19T06:36:00.000Z');

console.log(`\nfixedtz: ${ok} ок, ${bad} багов`);
process.exit(bad ? 1 : 0);
