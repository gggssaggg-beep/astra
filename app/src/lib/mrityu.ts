  'Меркурий': [15, 14, 13, 12, 8, 18, 20, 10, 21, 22, 7, 5],
  'Юпитер':   [19, 29, 12, 27, 6, 4, 13, 10, 17, 11, 15, 28],
  'Венера':   [28, 15, 11, 17, 10, 13, 4, 6, 27, 12, 29, 19],
  'Сатурн':   [10, 4, 7, 9, 12, 16, 3, 18, 28, 14, 13, 15],
  'Раху':     [14, 13, 12, 11, 24, 23, 22, 21, 10, 20, 18, 8],
