/** Тара дня: счёт накшатр от натальной Луны до сегодняшней (обе 1..27). */
export function taraOf(natalNak: number, dayNak: number): Tara {
  const count = ((dayNak - natalNak + 27) % 27) + 1;   // 1..27
  return TARAS[(count - 1) % 9];
}

