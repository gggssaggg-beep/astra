// ─── сводка: одна фраза о дне ───────────────────────────────────────────────
/** Главный текст экрана дня: накшатра ведёт, вара и пакша уточняют, трудная
 *  йога добавляет оговорку. Один абзац — остальное раскрывается по тапу
 *  (правило «один главный текст на экране»). */
export function dayHeadline(p: {
  varaDay: string; varaLord: string;
  tithiName: string; tithiIndex: number; paksha: 'шукла' | 'кришна';
  nakshatra: string; yoga: string;
}): string {
  const nak = NAKSHATRA_LORE[p.nakshatra] ?? '';
  const grow = p.paksha === 'шукла' ? 'Луна растёт' : 'Луна убывает';
  const yoga = YOGA_LORE[p.yoga];
  const tail = yoga && !yoga.good
    ? ` Йога дня трудная — ${yoga.text}: важное на такой день обычно не ставят.`
    : '';
  // группу титхи в сводку не тянем: на Пурниме выходило «Пурнима, пурна —
  // полная». Смысл группы раскрывается в строке «Титхи» по тапу.
  return `${nak} Днём правит ${p.varaLord} (${p.varaDay}), ${grow} — `
    + `${p.tithiName}.${tail}`;
}
