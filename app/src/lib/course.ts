/**
 * Курс «астрология с нуля» (слой 2 обучалки) — МОДЕЛЬ + программа из 8 уроков.
 *
 * Урок = тонкая обёртка-подача: свои — только короткие связки-подводки («ты»,
 * бытовой язык); вся глубина берётся из УЖЕ написанного:
 *  • glossKeys — чипы контекстной «?» (тап открывает GlossarySheet);
 *  • loreRef   — готовый длинный текст lore-модуля лениво (аккордеон на месте);
 *  • go        — кнопка «открой сам» → навигация в существующую шторку.
 * Ничего не дублируем.
 *
 * Микро-задание урока (quiz) строится по ЖИВОМУ небу дня: build(ctx) получает
 * позиции планет и аспекты и возвращает вопрос + варианты + индекс верного, ЛИБО
 * null — тогда данных нет (например планета выключена в объектах) и квиз просто
 * не показывается. Расчёт оффлайн, движок уже в App; кэш дня — общий.
 *
 * СЕЙЧАС наполнены текстом ДВА образцовых урока: `wheel` (1) и `aspects` (4) —
 * со всеми видами блоков и живым квизом. Остальные 6 — заглушки с правильными
 * id/emoji/title/intro; их blocks/quiz дополнит дешёвая модель партиями.
 */
import type { BodyPosition, AspectRecord } from '../engine/index.ts';
import { ZODIAC } from '../engine/index.ts';
import type { GlossSheet } from './glossary.ts';
import { ASPECT_LORE } from './lore.ts';

export interface LessonBlock {
  /** короткая подача (2–5 предложений, «ты») */
  text?: string;
  /** чипы «?»-терминов урока (тап = GlossarySheet) */
  glossKeys?: string[];
  /** готовый текст из lore-модуля (аккордеон); text ленивый — без тяжёлых импортов */
  loreRef?: { label: string; text: () => string };
  /** «открой сам» — навигация в существующую шторку */
  go?: { label: string; target: GlossSheet };
}

export interface LessonQuiz {
  /** Вопрос по живым данным дня. null = данных нет → квиз скрыть. */
  build: (ctx: { positions: BodyPosition[]; aspects: AspectRecord[] }) =>
    { q: string; options: string[]; correct: number } | null;
}

export interface Lesson {
  id: string;
  emoji: string;
  title: string;
  intro: string;
  blocks: LessonBlock[];
  quiz?: LessonQuiz;
}

// знак по эклиптической долготе (0..360°)
const signOfLon = (lon: number): string => ZODIAC[Math.floor(((lon % 360) + 360) % 360 / 30) % 12];

// перемешать и добить массив вариантов до нужной длины (варианты уникальны)
function shuffle<T>(arr: T[]): T[] {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

