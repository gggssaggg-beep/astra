/**
 * КАЛАМЫ И МУХУРТЫ — благоприятные и неблагоприятные отрезки светового дня.
 * Просьба астролога 12.08.2026 («раху калам, абхиджит мухурта, брахма мухурта
 * и т.д., с объяснениями по клику»), образец — приложение Vedic times.
 *
 * ОТКУДА ПРАВИЛА. Две из трёх «плохих» полос считать заново не пришлось: они
 * рождаются в частях суток, которыми правят конкретные грахи, а раскладка
 * частей уже есть в `upagraha.ts` (`partLord`) и сверена с астрологом
 * 06.08.2026. Гулика-калам — часть Сатурна, Ямаганда — часть Юпитера, ровно те
 * же части, где живут упаграхи Гулика и Ямагантака. Поэтому здесь ни одной
 * лишней таблицы: спросили ту же функцию.
 *
 * Своя таблица нужна только Раху-каламу: у Раху нет дня недели, которым он
 * правит, и его часть задана списком. Список сверен с показаниями Vedic times
 * на среду 12.08.2026 (см. проверку ниже) — но остальные шесть дней ждут
 * подтверждения астролога, см. docs/TEXTS_TO_REVIEW.md.
 *
 * СПОСОБ ПОДТВЕРЖДЁН АСТРОЛОГОМ 13.08.2026: взять восход и закат для НУЖНОЙ
 * ДАТЫ И МЕСТА, длину светового дня поделить на 8, от восхода отсчитать нужную
 * часть по дню недели. Отдельно предупредил: готовые таблицы с фиксированными
 * часами («понедельник 07:30–09:00») брать нельзя — границы плывут с широтой и
 * сезоном. Именно так здесь и считается: восход/закат приходят из Swiss
 * Ephemeris по координатам места, ни одного зашитого часа в файле нет.
 * Открытым остаётся только сам список номеров частей — RAHU_PART.
 *
 * ПРОВЕРКА. Снимок Vedic times за среду 12.08.2026 даёт: Яма Гхантак
 * 08:07–09:59, Гулика 11:51–13:43, Раху 13:43–15:34, Абхиджит 13:13–14:12,
 * Брахма 05:03–05:39. Отсюда длина части = 111 мин, восход ≈ 06:16, закат
 * ≈ 21:04. Наши формулы на тех же восходе и закате дают ровно эти окна:
 * Ямаганда — 2-я часть, Гулика — 4-я, Раху — 5-я, Абхиджит — середина дня
 * ±1/30 дня, Брахма — 14-я мухурта ночи из пятнадцати. Совпадение по всем
 * пяти полосам — не случайность, правила восстановлены верно.
 */
import { partLord, type DayFrame } from './upagraha.ts';

export type KalamKind = 'bad' | 'good';

export interface KalamWindow {
  name: string;
  from: Date;
  to: Date;
  kind: KalamKind;
  /** для полос-частей: номер части светового дня, 1..8 */
  part?: number;
}

/**
 * Часть светового дня, в которой сидит Раху, по дню недели (0 = вс).
 * У Раху нет своего дня недели, поэтому вывести часть из владык, как у Гулики
 * и Ямаганды, нельзя — только списком.
 */
export const RAHU_PART = [8, 2, 7, 5, 6, 4, 3];

/** Сколько равных частей делят световой день (для каламов). */
export const DAY_PARTS = 8;
/** Сколько мухурт в светлом и в тёмном отрезке по отдельности. */
export const MUHURTAS = 15;

const at = (start: Date, span: number, k: number): Date =>
  new Date(start.getTime() + span * k);

/** Найти номер части (1..7), которой правит указанная граха. */
const partOfLord = (frame: DayFrame, lord: string): number | null =>
  [1, 2, 3, 4, 5, 6, 7].find((k) => partLord(frame, k) === lord) ?? null;

/**
 * Каламы и мухурты суток, открытых восходом `frame.sunrise`.
 * Отсортированы по времени начала — как их и читают, сверху вниз.
 *
 * Считаем ВСЕГДА от светлого отрезка суток (восход → закат), даже если сам
 * момент ночной: каламы — это разметка дня, а не той половины, в которую
 * человек смотрит.
 */
export function kalamsOf(frame: DayFrame): KalamWindow[] {
  const dayMs = frame.sunset.getTime() - frame.sunrise.getTime();
  if (dayMs <= 0) return [];
  const partSpan = dayMs / DAY_PARTS;
  const out: KalamWindow[] = [];

  const band = (name: string, part: number | null): void => {
    if (!part) return;
    out.push({ name, kind: 'bad', part,
      from: at(frame.sunrise, partSpan, part - 1),
      to: at(frame.sunrise, partSpan, part) });
  };
  band('Раху-калам', RAHU_PART[frame.weekday] ?? null);
  band('Яма-ганда', partOfLord(frame, 'Юпитер'));
  band('Гулика-калам', partOfLord(frame, 'Сатурн'));

  // Абхиджит — восьмая мухурта дня из пятнадцати, то есть ровно середина
  // светлого отрезка. Единственный благоприятный отрезок среди этих полос.
  const dayMuhurta = dayMs / MUHURTAS;
  const midday = frame.sunrise.getTime() + dayMs / 2;
  out.push({ name: 'Абхиджит-мухурта', kind: 'good',
    from: new Date(midday - dayMuhurta / 2), to: new Date(midday + dayMuhurta / 2) });

  // Брахма-мухурта — предпоследняя мухурта НОЧИ (14-я из пятнадцати), то есть
  // две ночные мухурты до восхода. Ночь тут — от заката до следующего восхода,
  // и делится она своими пятнадцатью долями, не дневными: летом ночь короче,
  // и Брахма-мухурта вместе с ней.
  const nightMs = frame.nextSunrise.getTime() - frame.sunset.getTime();
  if (nightMs > 0) {
    const nightMuhurta = nightMs / MUHURTAS;
    out.push({ name: 'Брахма-мухурта', kind: 'good',
      from: new Date(frame.nextSunrise.getTime() - nightMuhurta * 2),
      to: new Date(frame.nextSunrise.getTime() - nightMuhurta) });
  }

  return out.sort((a, b) => +a.from - +b.from);
}

/** Идёт ли отрезок прямо сейчас (для подсветки «сейчас»). */
export const kalamNow = (w: KalamWindow, at: Date): boolean =>
  at >= w.from && at < w.to;

